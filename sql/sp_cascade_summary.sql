-- =============================================================================
-- SP_CASCADE_SUMMARY  |  Credit Campaign Analytics Dashboard
-- =============================================================================
-- Purpose : Orchestrates the full filter cascade pipeline for a given period,
--           populating the BD_CASCADAS_FINALES table consumed by the Power BI
--           Cascada tab.
--
-- Architecture (2-stage execution):
--   Stage 1 (@ETAPA=1):
--     - Copies MAESTRO_FILTROS from previous period
--     - Runs SP_CASCADAS_FILTROS_KILLER and SP_CASCADAS_FILTROS_DUROS
--     - Runs 12+ campaign-specific cascade sub-procedures:
--       APROBADOS : EAI, RECURRENTE, PILOTO1-4, REENGANCHE, PILOTO8-9, NUEVOS
--       EVALUABLES: EAI, BLINDAJE, ATAQUE
--
--   Stage 2 (@ETAPA=2):
--     - Consolidates all cascade outputs into BD_CASCADAS_FINALES
--     - Runs after the offer table (OfertaCamp) is refreshed by business team
--
-- Usage:
--   EXEC dbo.SP_CASCADE_SUMMARY '202601', 1   -- after master filter update
--   EXEC dbo.SP_CASCADE_SUMMARY '202601', 2   -- after offer table refresh
-- =============================================================================

